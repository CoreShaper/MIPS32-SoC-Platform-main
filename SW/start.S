# SW/start.S - MIPS 裸机启动代码（修正版）
.section .text.start
.globl _start
.type _start, @function

_start:
    # ------------------------------------------------------------
    # 1. 设置栈指针
    # ------------------------------------------------------------
    la    $sp, _stack_top         # $sp = r29，指向 RAM 顶部

    # ------------------------------------------------------------
    # 2. 清零 .bss 段（满足 C 语言运行环境要求）
    # ------------------------------------------------------------
    la    $t0, __bss_start        # $t0 = r8，BSS 起始地址
    la    $t1, __bss_end          # $t1 = r9，BSS 结束地址
    beq   $t0, $t1, 2f            # 若起始 == 结束（无 BSS 段），直接跳过
    nop
1:
    sw    $zero, 0($t0)           # 向当前地址写入 0
    addiu $t0, $t0, 4             # 指针加 4（下一个字）
    bne   $t0, $t1, 1b            # 未到达结束地址则继续循环
    nop
2:

    # ------------------------------------------------------------
    # 3. 跳转到 C 代码入口 main()
    # ------------------------------------------------------------
    jal   main                    # 调用 main，返回地址存入 $ra
    nop

    # ------------------------------------------------------------
    # 4. 若 main 返回，进入死循环（正常裸机程序不会返回）
    # ------------------------------------------------------------
3:
    j     3b
    nop

.size _start, . - _start